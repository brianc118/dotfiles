#!/usr/bin/env bash

# Deliberately NOT `set -e`. One unreachable git remote must not abandon the
# rest of the setup on a fresh host: a box with symlinked dotfiles but no fzf
# is far more useful than a box with nothing. Steps report through warn(), and
# the exit status still reflects whether anything failed.
set -x

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
PKGS_CENTOS="zsh vim neovim tmux git the_silver_searcher fd-find"
PKGS_DEBIAN="zsh vim neovim tmux git silversearcher-ag fd-find build-essential"
PKGS_DARWIN="zsh vim neovim tmux git fd tectonic wget karabiner-elements"
# Work hosts: installed via devfeature, not the distro package manager.
# zsh/vim/tmux/git are already present; fzf is deliberately omitted because we
# install it from git below to get the key bindings. tree_sitter_cli is needed
# by nvim-treesitter to build parsers.
FEATURES_META="neovim ripgrep fd bat tree_sitter_cli"
# Build deps for compiling mosh from source
MOSH_PKGS_DARWIN="protobuf boost pkg-config automake"

WARNINGS=0
warn() { echo "WARNING: $*" >&2; WARNINGS=$((WARNINGS + 1)); }

# ~/.gitconfig must be a REAL file that *includes* the copy in this repo -- not
# a symlink to it. `git config --global` writes to ~/.gitconfig, and plenty of
# things call it. With a symlink those machine-specific values land in a
# tracked file and get committed by accident.
#
# The include goes at the top, so anything appended later (which is where
# --global writes) takes precedence -- git applies config in file order.
# Runs before anything else here, because the proxy setup below uses --global.
ensure_real_gitconfig() {
  if [[ -L "$HOME/.gitconfig" ]]; then
    echo "Converting ~/.gitconfig from symlink to real file"
    rm -f "$HOME/.gitconfig"
  fi

  if [[ ! -e "$HOME/.gitconfig" ]]; then
    cat > "$HOME/.gitconfig" <<EOF
# Machine-local git config -- NOT tracked in the dotfiles repo.
# The shared config is included below; put host-specific settings (x509 certs,
# proxies, work email) here, or just let \`git config --global\` append them.
[include]
	path = $DIR/.gitconfig
EOF
  fi

  # Idempotent: only add the include if it isn't already there.
  if ! git config --global --get-all include.path 2>/dev/null \
    | grep -qxF "$DIR/.gitconfig"; then
    git config --global --add include.path "$DIR/.gitconfig"
  fi

  # Migrate the older ~/.gitconfig.local split into ~/.gitconfig, which is now
  # itself the machine-local file. Kept as a no-op once done.
  if [[ -f "$HOME/.gitconfig.local" ]]; then
    echo "Merging legacy ~/.gitconfig.local into ~/.gitconfig"
    cat "$HOME/.gitconfig.local" >> "$HOME/.gitconfig"
    mv "$HOME/.gitconfig.local" "$HOME/.gitconfig.local.migrated"
  fi
}

# Work hosts have no direct egress. The proxy settings (including a client
# cert) come from fwdproxy-config; don't hardcode them here.
CURL_PROXY_OPTS=()
# github.com and raw.githubusercontent.com only; internal hosts must keep
# talking direct.
PROXIED_GIT_HOSTS=("https://github.com/" "https://raw.githubusercontent.com/")

# Anything that shells out to curl -- nvim-treesitter fetching parser tarballs
# is the case that bites -- can see neither git's http.<url>.proxy config nor a
# client cert via http_proxy. A curlrc is the only form that carries all three
# (proxy, cert, key), so generate one. It lives in its own directory rather
# than ~/.curlrc so it can be opted into per-process with CURL_HOME (see the
# is_fb block in .vimrc) instead of silently reroute every curl on the box.
CURLRC_DIR="$HOME/.config/fwdproxy-curl"

write_curlrc() {
  mkdir -p "$CURLRC_DIR"
  local out="$CURLRC_DIR/.curlrc" i=0
  {
    echo "# Generated by dotfiles/install.sh from \`fwdproxy-config --format opts curl\`."
    echo "# Do not edit by hand -- re-run install.sh instead."
    while ((i < ${#CURL_PROXY_OPTS[@]})); do
      case "${CURL_PROXY_OPTS[i]}" in
        -p|--proxytunnel) echo "proxytunnel" ;;
        -x|--proxy)   echo "proxy = \"${CURL_PROXY_OPTS[$((i + 1))]}\"";      ((i++)) ;;
        --resolve)    echo "resolve = \"${CURL_PROXY_OPTS[$((i + 1))]}\"";    ((i++)) ;;
        --proxy-cert) echo "proxy-cert = \"${CURL_PROXY_OPTS[$((i + 1))]}\""; ((i++)) ;;
        --proxy-key)  echo "proxy-key = \"${CURL_PROXY_OPTS[$((i + 1))]}\"";  ((i++)) ;;
        --http1.1)    echo "http1.1" ;;
      esac
      i=$((i + 1))
    done
    # Internal hosts resolve and route directly; never send them to fwdproxy.
    echo "noproxy = .fbcdn.net,.facebook.com,.thefacebook.com,.tfbnw.net,.fb.com,.fburl.com,.facebook.net,.sb.fbsbx.com,localhost"
  } > "$out"
  echo "Wrote $out"
}

setup_proxy() {
  command -v fwdproxy-config >/dev/null 2>&1 || return 0
  echo "Detected Meta host -- routing outbound traffic via fwdproxy"

  # `fwdproxy-config --git-command git` emits `-c http.<key>=<value>` pairs on
  # one line (plus a deprecation warning on some builds, hence the grep).
  local tok
  local settings=()
  for tok in $(fwdproxy-config --git-command git 2>/dev/null | grep -v ThriftPyDeprecated); do
    [[ "$tok" == "-c" ]] && continue
    [[ "$tok" == http.*=* ]] || continue
    settings+=("$tok")
  done

  if ((${#settings[@]} == 0)); then
    warn "fwdproxy-config returned no git settings -- outbound clones may fail"
    return 0
  fi

  read -ra CURL_PROXY_OPTS <<< \
    "$(fwdproxy-config --format opts curl 2>/dev/null | grep -v ThriftPyDeprecated)"
  write_curlrc

  # Write it to git config rather than passing -c on each clone: the clones
  # below are not the only consumer. `:PlugInstall` from inside nvim, and any
  # manual `git clone` later, shell out to their own git and can only see what
  # is on disk.
  #
  # Rewrite the whole section each time rather than adding to it, so a
  # stale/incorrect value from an older version of this script cannot survive.
  # A per-URL key beats the generic `http.proxy`, so one bad entry here
  # silently defeats even a correct command line.
  #
  # --global is safe now that ensure_real_gitconfig has made ~/.gitconfig a
  # real, untracked file.
  local host s subkey value
  for host in "${PROXIED_GIT_HOSTS[@]}"; do
    git config --global --remove-section "http.${host}" 2>/dev/null
    for s in "${settings[@]}"; do
      subkey="${s%%=*}"; subkey="${subkey#http.}"
      value="${s#*=}"
      git config --global "http.${host}.${subkey}" "$value"
    done
  done

  # Deliberately no http_proxy/HTTPS_PROXY exports: the env-var form cannot
  # carry a client cert. git reads the config written above; curl gets
  # CURL_PROXY_OPTS.
}

# Clone only if the destination is missing, without letting a failure take down
# the rest of the script. No -c flags needed: setup_proxy has already written
# the proxy into ~/.gitconfig by the time this runs.
git_clone() {
  local url="$1" dest="$2"; shift 2
  [[ -e "$dest" ]] && return 0
  echo "Cloning $url -> $dest"
  git clone "$@" "$url" "$dest" \
    || { warn "could not clone $url -- skipping"; rm -rf "$dest"; return 1; }
}

proxy_curl() {
  curl "${CURL_PROXY_OPTS[@]}" "$@"
}

install() {
  cd ~
  # Figure out which package manager to use
  platform=$(uname)
  if [[ $platform == 'Linux' ]] && command -v devfeature >/dev/null 2>&1; then
    # Work host. Use devfeature rather than dnf: a direct install is unmanaged
    # and does not survive host rotation, while `devfeature persist`
    # re-installs the feature on every host reserved from here on.
    echo "Meta host detected -- installing features with devfeature"
    for feat in $FEATURES_META; do
      devfeature install "$feat" \
        || { warn "devfeature install $feat failed -- skipping"; continue; }
      devfeature persist "$feat" \
        || warn "devfeature persist $feat failed (installed but not persisted)"
    done
  elif [[ $platform == 'Linux' ]]; then
    if [[ -f /etc/redhat-release ]]; then
      PKG_MANAGER_CMD="sudo dnf install -y"
      PKGS="$PKGS_CENTOS"
    elif [[ -f /etc/debian_version ]]; then
      PKG_MANAGER_CMD="sudo apt-get install -y"
      PKGS="$PKGS_DEBIAN"
    elif [[ -f /etc/arch-release ]]; then
      PKG_MANAGER_CMD="sudo pacman -S --noconfirm"
      PKGS="$PKGS_CENTOS"
    else
      echo "Unhandled Linux distro -- giving up forever"
      exit 1
    fi
    # Install one at a time: on locked-down hosts some of these
    # aren't in the configured repos, and a single missing package would
    # otherwise abort the whole script.
    for pkg in $PKGS; do
      $PKG_MANAGER_CMD "$pkg" || warn "could not install $pkg -- skipping"
    done
  elif [[ $platform == 'Darwin' ]]; then
    if ! command -v brew &> /dev/null; then
      echo "Installing homebrew"
      /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
    fi
    echo "Installing packages" $PKGS_DARWIN $MOSH_PKGS_DARWIN "with brew install"
    export HOMEBREW_NO_AUTO_UPDATE=1
    brew install $PKGS_DARWIN $MOSH_PKGS_DARWIN || warn "brew install failed"
  fi

  # Each of these is independent: a failure to reach github for one must not
  # skip the others (prezto being first is what previously took out fzf, tpm,
  # vim-plug, the symlinks, and post_install in one go).
  git_clone https://github.com/brianc118/prezto.git ~/.zprezto --recursive

  # Could use package manager here but doesn't install key bindings by default.
  # The `--all` installer appends its own source lines to ~/.zshrc, which is a
  # symlink into this repo -- so it must only ever run on a fresh clone, never
  # on every bootstrap.
  if [[ ! -d ~/.fzf ]]; then
    if git_clone https://github.com/junegunn/fzf.git ~/.fzf --depth 1; then
      ~/.fzf/install --all || warn "fzf install script failed"
    fi
  fi

  if [[ ! -f ~/.vim/autoload/plug.vim ]]; then
    echo "Installing vim-plug"
    proxy_curl -fLo ~/.vim/autoload/plug.vim --create-dirs \
      https://raw.githubusercontent.com/junegunn/vim-plug/master/plug.vim \
      || warn "could not download vim-plug"
  fi

  if [[ ! -f ~/.local/share/nvim/site/autoload/plug.vim ]]; then
    echo "Installing vim-plug (nvim)"
    proxy_curl -fLo ~/.local/share/nvim/site/autoload/plug.vim --create-dirs \
      https://raw.githubusercontent.com/junegunn/vim-plug/master/plug.vim \
      || warn "could not download vim-plug for nvim"
  fi

  git_clone https://github.com/tmux-plugins/tpm ~/.tmux/plugins/tpm
}

# Language server extensions for the work LSP setup. They come from a bundle
# that only exists on work hosts, so skip the sync when it is absent.
#
# nvim also syncs these on startup, so the `+PlugInstall` runs above can start
# a sync and exit out from under it, leaving a half-installed state. Doing it
# here explicitly, and waiting, avoids that.
sync_meta_ls() {
  if ! compgen -G "/usr/local/fbpkg/vscodefb/vscode-server/*" >/dev/null \
    && ! compgen -G "/usr/local/fbpkg/nuclide/vscode-server/*" >/dev/null; then
    echo "NOTE: no vscode-server bundle found; skipping Meta LS extension sync."
    return 0
  fi

  # The sync is asynchronous, so wait for its completion event, with a bounded
  # timeout so a wedged sync cannot hang the bootstrap forever.
  echo "Syncing Meta LS extensions (SyncMetaLS)"
  nvim --headless -u ~/.config/nvim/init.vim \
    -c 'lua vim.g.__bootstrap_ls_done = false' \
    -c 'lua vim.api.nvim_create_autocmd("User", { pattern = "SyncMetaLSComplete", callback = function() vim.g.__bootstrap_ls_done = true end })' \
    -c 'lua require("meta.lsp").sync_vscode_extensions(true)' \
    -c 'lua if not vim.wait(600000, function() return vim.g.__bootstrap_ls_done end, 200) then vim.cmd("cquit") end' \
    +qa </dev/null \
    || warn "Meta LS sync did not complete -- run :SyncMetaLS inside nvim"
}

nvim_uses_treesitter_main() {
  nvim --headless --clean \
    -c 'if !has("nvim-0.12") | cquit | endif' \
    +qa </dev/null >/dev/null 2>&1
}

# nvim-treesitter's main branch (Neovim 0.12+) compiles parsers with
# `tree-sitter build`, and needs tree-sitter-cli 0.26.1 or newer for it.
tree_sitter_cli_is_compatible() {
  local version
  version="$(tree-sitter --version 2>/dev/null)" || return 1
  [[ "$version" =~ ([0-9]+)\.([0-9]+)\.([0-9]+) ]] || return 1

  local major="${BASH_REMATCH[1]}"
  local minor="${BASH_REMATCH[2]}"
  local patch="${BASH_REMATCH[3]}"
  ((major > 0 || minor > 26 || (minor == 26 && patch >= 1)))
}

# The compatibility check above swallows stderr so it can be used as a quiet
# predicate. When it fails, say *why* -- "requires 0.26.1 or newer" printed
# over a binary that is actually crashing on exec is how the glibc problem
# below went unnoticed for three bootstrap attempts.
describe_tree_sitter_cli() {
  local bin
  bin="$(command -v tree-sitter)" || { echo "    tree-sitter: not on PATH"; return 0; }
  echo "    $bin: $("$bin" --version 2>&1 | head -3 | tr '\n' ' ')"
}

# cargo cannot present a client cert to the proxy, so it needs a proxy
# listener that does not require one. That is not available on every host, so
# probe it instead of assuming.
CARGO_FWDPROXY="http://fwdproxy:8080"

run_cargo() {
  if ! command -v fwdproxy-config >/dev/null 2>&1; then
    cargo "$@"
    return
  fi
  if ! curl -sSf -o /dev/null --max-time 20 -x "$CARGO_FWDPROXY" \
      https://index.crates.io/config.json; then
    echo "cargo needs the ttls fwdproxy ($CARGO_FWDPROXY), and it cannot reach crates.io." >&2
    echo "See https://www.internalfb.com/intern/wiki/Traffic/Proxygen/Forward_Proxy/Client_Certificates/Devservers/" >&2
    return 1
  fi
  CARGO_HTTP_PROXY="$CARGO_FWDPROXY" cargo "$@"
}

# cargo is only needed at install time, to build tree-sitter-cli. Work hosts
# usually have it already, so the fallbacks are for anywhere else. A direct dnf
# install is acceptable here despite the devfeature reasoning in install():
# nothing needs cargo after this script finishes.
ensure_cargo() {
  command -v cargo >/dev/null 2>&1 && return 0
  if [[ -x "$HOME/.cargo/bin/cargo" ]]; then  # rustup, not yet on PATH
    export PATH="$HOME/.cargo/bin:$PATH"
    return 0
  fi
  echo "cargo not found -- installing it"
  case "$(uname)" in
    Linux)
      if [[ -f /etc/redhat-release ]]; then
        sudo -n dnf install -y cargo
      elif [[ -f /etc/debian_version ]]; then
        sudo -n apt-get install -y cargo
      fi
      ;;
    Darwin) HOMEBREW_NO_AUTO_UPDATE=1 brew install rust ;;
  esac
  command -v cargo >/dev/null 2>&1
}

# Build tree-sitter-cli from source with cargo; do NOT download the prebuilt
# release binary. The Linux binaries on GitHub releases are linked on a current
# Ubuntu runner and need glibc 2.39, while CentOS Stream 9 has 2.34. The
# download "succeeds", then dies at exec with `GLIBC_2.39 not found`. Compiling
# here links against the host's own glibc, so that cannot happen. The packaged
# tree-sitter is no help either: it is 0.25.x, too old for nvim-treesitter's
# main branch.
install_tree_sitter_cli() {
  nvim_uses_treesitter_main || return 0
  export PATH="$HOME/.local/bin:$PATH"
  tree_sitter_cli_is_compatible && return 0

  # A tree-sitter in ~/.local/bin that cannot even run -- in practice the
  # glibc-2.39 download an older version of this script left there -- shadows
  # the /usr/bin one (~/.local/bin is first on PATH), and cargo refuses to
  # overwrite a binary it did not install. Clear it first.
  local dest="$HOME/.local/bin/tree-sitter"
  if [[ -e "$dest" ]] && ! "$dest" --version >/dev/null 2>&1; then
    echo "Removing $dest, which does not run:"
    "$dest" --version 2>&1 | head -3 | sed 's/^/    /'
    rm -f "$dest"
    hash -r
  fi

  ensure_cargo || { echo "no cargo available to build tree-sitter-cli" >&2; return 1; }

  # --root ~/.local puts the binary in ~/.local/bin, which is already first on
  # PATH, so no ~/.cargo/bin PATH setup is needed. --locked builds with the
  # crate's own Cargo.lock, so a newly released dependency cannot break the
  # build. --force because we only get here when the installed one is missing
  # or too old, and cargo otherwise refuses to replace a binary.
  echo "Building tree-sitter-cli with cargo (takes a few minutes)"
  run_cargo install --locked --force --root "$HOME/.local" tree-sitter-cli \
    || return 1
  hash -r
  tree_sitter_cli_is_compatible
}

migrate_legacy_treesitter_parsers() {
  nvim_uses_treesitter_main || return 0

  local plugin_dir="$HOME/.vim/plugged/nvim-treesitter"
  if [[ ! -d "$plugin_dir/parser" && ! -d "$plugin_dir/parser-info" ]]; then
    return 0
  fi

  local backup
  backup="$HOME/.cache/nvim/nvim-treesitter-master-parsers-$(date +%s)"
  mkdir -p "$backup"
  [[ ! -d "$plugin_dir/parser" ]] || mv "$plugin_dir/parser" "$backup/"
  [[ ! -d "$plugin_dir/parser-info" ]] || mv "$plugin_dir/parser-info" "$backup/"
  echo "Moved legacy nvim-treesitter parsers to $backup"
}

update_nvim_treesitter_main() {
  local plug="$HOME/.local/share/nvim/site/autoload/plug.vim"
  [[ -f "$plug" ]] || return 1

  nvim --headless -u NONE \
    -c "source $plug" \
    -c "call plug#begin('$HOME/.vim/plugged')" \
    -c "Plug 'nvim-treesitter/nvim-treesitter', {'branch': 'main'}" \
    -c 'call plug#end()' \
    -c 'PlugUpdate nvim-treesitter' \
    +qa </dev/null
}

post_install () {
  echo "Post Install"
  cd "$DIR"
  # vim-plug exits non-zero from silent-ex mode even on a clean install, so
  # don't let a failure here be reported as one.
  command -v vim  >/dev/null && { vim  -es -u ~/.vimrc                 +PlugInstall +qa </dev/null || true; }

  command -v nvim >/dev/null || { echo "no nvim; skipping parser and LS setup"; return 0; }

  if nvim_uses_treesitter_main; then
    update_nvim_treesitter_main \
      || warn "could not update nvim-treesitter to its Neovim 0.12 branch"
    migrate_legacy_treesitter_parsers
    if ! install_tree_sitter_cli; then
      warn "could not install tree-sitter-cli >= 0.26.1 (needed by nvim-treesitter); found:"
      describe_tree_sitter_cli >&2
    fi
  fi

  nvim -es -u ~/.config/nvim/init.vim +PlugInstall +qa </dev/null || true

  # Build the treesitter parsers synchronously so headless nvim cannot exit
  # before the asynchronous install/update work finishes. Neovim 0.12 uses the
  # rewritten nvim-treesitter API; older releases still provide TSUpdateSync.
  if nvim_uses_treesitter_main && ! tree_sitter_cli_is_compatible; then
    echo "Skipping parser setup until tree-sitter-cli 0.26.1 or newer is available"
  elif [[ -d "$HOME/.vim/plugged/nvim-treesitter" ]]; then
    echo "Building treesitter parsers"
    # A Lua error in a -c command does NOT make nvim exit non-zero: it prints
    # E5108 and carries on to +qa, which exits 0. So catch the error and
    # cquit explicitly, or a failed parser build is reported as success.
    nvim --headless -u ~/.config/nvim/init.vim \
      -c "lua local ok, err = pcall(function() if vim.fn.has('nvim-0.12') == 1 then local ts = require('nvim-treesitter'); local langs = vim.g.dotfiles_treesitter_languages; assert(ts.install(langs):wait(300000)); assert(ts.update(langs):wait(300000)) else vim.cmd('TSUpdateSync') end end); if not ok then io.stderr:write(tostring(err) .. '\n'); vim.cmd('cquit 1') end" \
      +qa </dev/null \
      || warn "treesitter parser setup failed -- run :TSUpdate inside nvim"
  fi

  sync_meta_ls

  echo "You may also want to install"
  echo "bat"
}

symlinks () {
  echo "Symlinks"
  cd "$DIR"
  [[ ! -f "$HOME/.arcrc" ]] || chmod 600 "$HOME/.arcrc"
  # NB: .gitconfig is deliberately not symlinked -- see ensure_real_gitconfig.
  ln -sf "$DIR/.zshrc" ~
  ln -sf "$DIR/.zpreztorc" ~
  ln -sf "$DIR/.vimrc" ~
  ln -sf "$DIR/.tmux.conf" ~
  ln -sf "$DIR/.alacritty.toml" ~

  mkdir -p ~/.config/nvim
  ln -sf "$DIR/init.vim" ~/.config/nvim/init.vim

  # Karabiner rewrites karabiner.json in place, so symlink the whole directory
  # rather than the file. Karabiner recreates this dir with a default config on
  # first launch, so move any real directory aside before linking.
  if [[ ! -L ~/.config/karabiner ]]; then
    if [[ -e ~/.config/karabiner ]]; then
      mv ~/.config/karabiner ~/.config/karabiner.bak."$(date +%Y%m%d%H%M%S)"
    fi
    ln -sfn "$DIR/.config/karabiner" ~/.config/karabiner
  fi

  mkdir -p ~/.local/bin
  ln -sf "$DIR/rebase.sh" ~/.local/bin
  ln -sf "$DIR/yes2.sh" ~/.local/bin/yes2
}

ensure_real_gitconfig
setup_proxy
# Symlinks first: they need no network, so they must not be collateral damage
# from an egress problem during install().
symlinks
install
post_install

if ((WARNINGS)); then
  echo "install.sh finished with $WARNINGS warning(s)"
  exit 1
fi
